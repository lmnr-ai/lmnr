import assert from 'node:assert/strict';
import {ultimate2ClickTracks, clickEventsBetween, clickPhaseAt, clickRate, COST_PURPLE_CLICK, COST_YELLOW_CLICK, midiFrequency, SOFT_PAWL_CLICK, type ClickTrack} from './ratchet-click';
import {costClickTracks} from './micro-16/cost-ratchet';
import {DEFAULT_TIMING} from './micro-16/timeline';
import {sampleMicro17} from './micro-17/sample';
import {sampleMicro16} from './micro-16/sample';
import {agentScreenPan, worldState} from './micro-17/geometry';

assert.equal(clickRate(SOFT_PAWL_CLICK), 9.54, 'supplied speed/teeth produce exactly 9.54 clicks/s');
assert.equal(SOFT_PAWL_CLICK.note, 55); assert.equal(SOFT_PAWL_CLICK.clickDecay, 62);
assert.equal(SOFT_PAWL_CLICK.clickTone, .25); assert.equal(SOFT_PAWL_CLICK.volume, .41);
assert.ok(midiFrequency(COST_YELLOW_CLICK.note) > midiFrequency(COST_PURPLE_CLICK.note));
assert.ok(clickRate(COST_YELLOW_CLICK) > clickRate(COST_PURPLE_CLICK));

const base: ClickTrack = {id: 'base', start: 1, end: 4, preset: SOFT_PAWL_CLICK, rateScaleAt: t => .4 + .6 * ((t - 1) / 3)};
const whole = Array.from({length: 15}, (_, i) => clickEventsBetween(1 + i * .2, Math.min(3.9, 1 + (i + 1) * .2), [base])).flat();
const partitioned = Array.from({length: 29}, (_, i) => clickEventsBetween(1 + i * .1, 1 + (i + 1) * .1, [base])).flat();
assert.deepEqual(partitioned.map(e => e.time.toFixed(8)), whole.map(e => e.time.toFixed(8)), 'absolute phase crossings are partition invariant');
const irregular = [1,1.07,1.19,1.41,1.58,1.79,1.98,2.17,2.39,2.61,2.8,3.01,3.2,3.41,3.63,3.79,3.9].slice(1).flatMap((t,i,a) => clickEventsBetween(i ? a[i-1] : 1,t,[base]));
assert.deepEqual(irregular.map(e => e.time.toFixed(8)), whole.map(e => e.time.toFixed(8)), 'irregular clocks emit the same phase crossings');
assert.deepEqual(clickEventsBetween(2, 1.9, [base]), []); assert.deepEqual(clickEventsBetween(1, 2, [base]), [], 'large seek does not catch up');
assert.ok(clickPhaseAt(base, 3) > clickPhaseAt(base, 2));
assert.notEqual(agentScreenPan(worldState(sampleMicro17(11))), agentScreenPan(worldState(sampleMicro17(8))), 'Ultimate 2 pan follows its moving camera during the audible tail');

const tracks = costClickTracks();
const yellow = tracks.filter(t => t.id.includes('yellow'));
assert.equal(yellow.length, 3, 'all three visible row passes have distinct tracks');
const yellowEvents = [...clickEventsBetween(1.39, 1.6, yellow), ...clickEventsBetween(1.6, 1.81, yellow)];
assert.ok(yellowEvents.length >= 3, 'short yellow pass retains several fast clicks');
const middle = yellow[1];
assert.ok((middle.panAt?.(1.91) ?? 0) > (middle.panAt?.(2.27) ?? 0), 'middle leftward pass pans opposite the rightward rows');
const right = tracks.find(t => t.id === 'cost-purple-bash-right')!;
assert.equal(right.start, DEFAULT_TIMING.purpleBashEntry.at);
assert.equal(right.end, Math.max(DEFAULT_TIMING.purpleBashEntry.at + DEFAULT_TIMING.purpleBashEntry.duration, DEFAULT_TIMING.purpleBashStop.at + DEFAULT_TIMING.purpleBashStop.duration), 'overlapping right clips form one union voice');
assert.ok((right.rateScaleAt?.(6.09) ?? 0) > (right.rateScaleAt?.(6.32) ?? 1));
assert.equal(right.rateScaleAt?.(right.end), 0, 'rightward stop reaches zero cadence');
const down = tracks.find(t => t.id === 'cost-purple-bash-down')!;
assert.equal(down.rateScaleAt?.(down.start), 0); assert.ok((down.rateScaleAt?.((down.start + down.end) / 2) ?? 0) > .9); assert.ok((down.rateScaleAt?.(down.end) ?? 1) < 1e-9);
assert.ok(down.start > right.end, 'stationary purple gap is silent before downward restart');
const budget = tracks.find(t => t.id === 'cost-purple-budget')!;
assert.ok((budget.rateScaleAt?.(11.5) ?? 0) > (budget.rateScaleAt?.(13.6) ?? 1));
assert.ok((budget.rateScaleAt?.(budget.end) ?? 1) < 1e-9, 'budget depletion ends at zero cadence');
const shifted = costClickTracks({}, {}, 20, 12);
assert.equal(shifted[0].start, yellow[0].start + 20, 'composition chapter offset is applied');
assert.ok(shifted.every(track => track.end <= 32), 'composition trim bounds every Cost track');
assert.deepEqual(ultimate2ClickTracks({at: 2, duration: 0}), [], 'instant/disabled stream never creates a phantom three-second click tail');
const trimmedStream = ultimate2ClickTracks({at: 2, duration: 10}, undefined, 5);
assert.equal(trimmedStream[0].end, 5, 'Ultimate 3 source hold/chapter end bounds stream clicks');
assert.deepEqual(ultimate2ClickTracks({at: 7, duration: 2}, undefined, 5), [], 'trim before stream start stays silent');
const cameraTiming = {budgetRun: {at: 0, duration: 1}, budgetDepletion: {at: 100, duration: 1}};
const cameraYellow = costClickTracks(cameraTiming)[0];
const cameraState = sampleMicro16(1.6, {}, cameraTiming);
const expectedPan = Math.max(-1, Math.min(1, (cameraState.cheapAgents[0].x - cameraState.camera.x - 640) / 640));
assert.equal(cameraYellow.panAt?.(1.6), expectedPan, 'yellow pan subtracts a retimed moving camera');
assert.equal(cameraYellow.gainAt?.(1.42), 0, 'camera can carry a yellow agent fully off screen');
const separated = costClickTracks({purpleBashEntry: {at: 2, duration: .3}, purpleBashStop: {at: 4, duration: .3}}).find(t => t.id === 'cost-purple-bash-right')!;
assert.equal(separated.rateScaleAt?.(3), 0, 'a retimed gap between rightward clips has zero cadence');
console.log('ratchet-click tests passed');
