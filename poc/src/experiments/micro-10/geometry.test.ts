import assert from 'node:assert/strict';
import {CELL, CLOUD, MICRO_10_DEFAULTS, STREAM_PERIOD, sampleMicro10} from './geometry';

const near = (actual: number, expected: number) => assert.ok(Math.abs(actual - expected) < 1e-7, `${actual} != ${expected}`);
const start = sampleMicro10(0);
near(start.cloudBounds.width, CLOUD.width * (1 - MICRO_10_DEFAULTS.widthAmount) * (1 - MICRO_10_DEFAULTS.shrinkAmount));
near(start.cloudBounds.height, CLOUD.height * (1 + MICRO_10_DEFAULTS.heightAmount) * (1 - MICRO_10_DEFAULTS.shrinkAmount));
near(start.cloudBounds.x + start.cloudBounds.width, CLOUD.right);
near(start.cloudBounds.y + start.cloudBounds.height, CLOUD.bottom);
const opposite = sampleMicro10(MICRO_10_DEFAULTS.squishPeriod / 2);
near(opposite.cloudBounds.width, CLOUD.width * (1 + MICRO_10_DEFAULTS.widthAmount));
near(opposite.cloudBounds.height, CLOUD.height * (1 - MICRO_10_DEFAULTS.heightAmount));
assert.ok(opposite.cloudBounds.width > start.cloudBounds.width, 'scale returns to 1 at maximum width');
near(opposite.cloudBounds.x + opposite.cloudBounds.width, CLOUD.right);
near(opposite.cloudBounds.y + opposite.cloudBounds.height, CLOUD.bottom);
assert.deepEqual(sampleMicro10(MICRO_10_DEFAULTS.squishPeriod).cloudBounds, start.cloudBounds, 'squish cycle closes');
assert.equal(STREAM_PERIOD % CELL, 0, 'stream tile closes on a grid line');
near(sampleMicro10(STREAM_PERIOD / MICRO_10_DEFAULTS.streamerSpeed).streamPhase, 0);
near(sampleMicro10(CELL / MICRO_10_DEFAULTS.streamerSpeed).gridPhase, 0);
near(sampleMicro10(.1).gridPhase, sampleMicro10(.1).streamPhase % CELL);
assert.equal(sampleMicro10(.01).cloudBounds.width, start.cloudBounds.width, 'pose holds within a stepped frame');
assert.notEqual(sampleMicro10(MICRO_10_DEFAULTS.squishPeriod / 8).cloudBounds.width, start.cloudBounds.width, 'pose changes at a frame boundary');
const emission = sampleMicro10(MICRO_10_DEFAULTS.squishPeriod / 2);
assert.equal(emission.puffs[0].progress, 0, 'puff emits exactly at maximum width');
near(emission.puffs[0].bounds.x + emission.puffs[0].bounds.width, CLOUD.right - CLOUD.width + MICRO_10_DEFAULTS.puffXOffset);
near(emission.puffs[0].bounds.y, CLOUD.bottom - CLOUD.height + MICRO_10_DEFAULTS.puffYOffset);
const nextEmission = sampleMicro10(MICRO_10_DEFAULTS.squishPeriod * 1.5);
assert.equal(nextEmission.puffs[0].progress, 0, 'one new puff emits each period');
assert.ok(nextEmission.puffs[1].bounds.width < nextEmission.puffs[0].bounds.width, 'older puff scales down');
assert.ok(nextEmission.puffs[1].bounds.x < nextEmission.puffs[0].bounds.x, 'older puff travels left');
assert.ok(nextEmission.puffs.every(puff => puff.phaseOffset >= 0 && puff.phaseOffset < MICRO_10_DEFAULTS.squishPeriod));
assert.notEqual(nextEmission.puffs[0].phaseOffset, nextEmission.puffs[1].phaseOffset, 'each puff gets an independent phase');
assert.deepEqual(sampleMicro10(MICRO_10_DEFAULTS.squishPeriod * 1.5), nextEmission, 'seeded phases are deterministic');
const otherSeed = sampleMicro10(MICRO_10_DEFAULTS.squishPeriod * 1.5, {...MICRO_10_DEFAULTS, puffRandomSeed: 210});
assert.notEqual(otherSeed.puffs[0].phaseOffset, nextEmission.puffs[0].phaseOffset, 'seed changes puff phases');
const retimedPuff = sampleMicro10(.1, MICRO_10_DEFAULTS, {at: .1, duration: .8});
assert.equal(retimedPuff.puffs[0].progress, 0, 'dragging the puff bar moves the first visual emission');
assert.equal(sampleMicro10(.9, MICRO_10_DEFAULTS, {at: .1, duration: .8}).puffs[0].progress, 0, 'the puff bar duration controls the repeating visual interval');
console.log('Micro10 geometry: anchored squash, seeded independent puff phases, periodic shrinking puffs, and streamer loop passed.');
