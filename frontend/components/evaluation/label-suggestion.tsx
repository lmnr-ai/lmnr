import { type ColumnDef } from "@tanstack/react-table";

import {
  type ActiveSuggestion,
  type ColumnSuggestion,
  SuggestedColumnHeader,
} from "@/components/ui/columns-menu/suggestions";
import { type EvalRow } from "@/lib/evaluation/types";

import { DataCell } from "./columns/data-cell";

export const LABEL_SUGGESTION_ID = "label";
export const LABEL_SUGGESTION_NAME = "Label";

// Fixed task prompt for the "Label" suggestion: extract a concise identifier.
const LABEL_INSTRUCTION =
  "Produce a ClickHouse SQL expression that extracts a short, human-readable identifier for each evaluation datapoint " +
  "from its `data`, `target`, or `metadata` JSON columns \u2014 something a reviewer can use to tell rows apart at a glance " +
  "(e.g. a name, id, title, question, or key input field). Prefer a real identifier key over a raw text dump; fall back to " +
  "a short prefix of the most descriptive field only if nothing better exists.";

/** The eval-table "Label" suggestion, generated by the agentic column-SQL writer. */
export function createLabelSuggestion(projectId: string, evaluationId: string): ColumnSuggestion {
  return {
    id: LABEL_SUGGESTION_ID,
    name: LABEL_SUGGESTION_NAME,
    dataType: "string",
    generate: async () => {
      const res = await fetch(`/api/projects/${projectId}/sql/generate-column`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          table: "evaluation_datapoints",
          whereSql: "evaluation_id = {evaluationId:UUID}",
          parameters: { evaluationId },
          sampleColumns: ["data", "target", "metadata"],
          instruction: LABEL_INSTRUCTION,
          dataType: "string",
        }),
      });
      // Non-2xx = transient (throw so the hook retries next mount, not resolve).
      if (!res.ok) throw new Error(`generate-column failed: ${res.status}`);
      const json = (await res.json()) as { success?: boolean; sql?: string; reason?: "none" | "error" };
      if (json.success && json.sql) return { sql: json.sql };
      // Agent definitively found no identifier -> resolve. Anything else is transient.
      if (json.reason === "none") return null;
      throw new Error("generate-column produced no result");
    },
  };
}

/** Build the ephemeral column defs for currently-active suggestions. */
export function buildSuggestedColumnDefs(
  active: ActiveSuggestion[],
  keep: (id: string) => void,
  discard: (id: string) => void
): ColumnDef<EvalRow>[] {
  return active.map(({ suggestion, sql }) => {
    const columnId = `custom:${suggestion.name}`;
    return {
      id: columnId,
      accessorFn: (row) => row[columnId],
      cell: DataCell,
      header: () => (
        <SuggestedColumnHeader
          name={suggestion.name}
          onKeep={() => keep(suggestion.id)}
          onDiscard={() => discard(suggestion.id)}
        />
      ),
      enableSorting: false,
      meta: {
        sql,
        dataType: suggestion.dataType,
        isCustom: true,
        suggested: true,
        // Transient — keep it out of the filter UI and comparison join.
        filterable: false,
        comparable: false,
      },
    };
  });
}
