#!/usr/bin/env node
/*
 * Counts rough call-sites per color token across the frontend and writes ./color-counts.ts
 * (imported by the style-explorer color sections). For each token it collapses every Tailwind
 * color prefix (bg/text/border/ring/fill/stroke/from/to/via/decoration/outline/shadow/accent/
 * caret/divide, plus /opacity variants) AND direct CSS `var(--token)` / `hsl(var(--token))`
 * references into one number, so a count of 0 means the color is genuinely unused.
 *
 * Token names are read from ./tokens.ts so the two stay in sync. The style-explorer + ui-gallery
 * (demos) are excluded so they don't inflate counts; globals.css IS scanned so a token used only
 * via a semantic alias (e.g. --destructive: var(--red)) still counts as used, not falsely dead.
 * Rough by design. Run from frontend/: node components/style-explorer/gen-color-counts.cjs
 */
const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const dir = __dirname;
const FE = path.resolve(dir, "../..");

// --- token names to count, derived from tokens.ts ---
const tokensSrc = fs.readFileSync(path.join(dir, "tokens.ts"), "utf8");
const names = new Set();
// Scale stops: `key: "surface-100"` in SURFACE_SEED / FOREGROUND_SEED.
for (const m of tokensSrc.matchAll(/key:\s*"([a-z][a-z0-9-]*)"/g)) names.add(m[1]);
// CSS var names: `"--red"`, `"--color-primary-400"` in the seed records -> base name.
for (const m of tokensSrc.matchAll(/"--(?:color-)?([a-z][a-z0-9-]*)"/g)) names.add(m[1]);

// --- collect source once, tally generically, then filter by the name set ---
const files = execSync(
  "rg --files -g '*.tsx' -g '*.ts' -g '*.css' -g '!components/style-explorer/**' -g '!components/ui-gallery/**' app components lib",
  { cwd: FE, encoding: "utf8", maxBuffer: 128 * 1024 * 1024 }
)
  .split("\n")
  .filter(Boolean);

const PREFIXES = "bg|text|border|ring|ring-offset|fill|stroke|from|to|via|decoration|outline|shadow|accent|caret|divide";
// A Tailwind color utility: prefix-<name> with an optional /opacity, not followed by more word/dash
// (so `bg-red` is counted but `bg-red-500` — a different token — is not).
const utilRe = new RegExp(`(?:${PREFIXES})-([a-z][a-z0-9-]*?)(?:\\/\\d+)?(?![\\w-])`, "g");
const varRe = /var\(\s*--(?:color-)?([a-z][a-z0-9-]*)\s*[)/,\s]/g;

const counts = {};
for (const name of names) counts[name] = 0;

for (const rel of files) {
  const src = fs.readFileSync(path.join(FE, rel), "utf8");
  for (const m of src.matchAll(utilRe)) if (counts[m[1]] !== undefined) counts[m[1]]++;
  for (const m of src.matchAll(varRe)) if (counts[m[1]] !== undefined) counts[m[1]]++;
}

const body = [...names]
  .sort()
  .map((name) => `  "${name}": ${counts[name]},`)
  .join("\n");
const out = `// GENERATED by ./gen-color-counts.cjs — do not edit by hand.
// Rough count of call-sites per color token across the frontend (Tailwind color prefixes +
// /opacity variants + direct var()/hsl(var()) refs), excluding the style-explorer, ui-gallery,
// and globals.css. A 0 means the color is unused. Regenerate after color refactors.
export const colorCounts: Record<string, number> = {
${body}
};
`;
fs.writeFileSync(path.join(dir, "color-counts.ts"), out);
console.log(`wrote color-counts.ts for ${names.size} tokens`);
console.log(
  [...names]
    .sort((a, b) => counts[b] - counts[a])
    .map((n) => `  ${n}: ${counts[n]}`)
    .join("\n")
);
