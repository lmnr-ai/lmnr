#!/usr/bin/env node
/*
 * Counts JSX callsites of each gallery component across the frontend and writes
 * ./callsite-counts.ts (imported by the gallery sidebar). A "callsite" is a JSX
 * usage `<Name` bounded by whitespace / `>` / `/` — so `<Table` doesn't match
 * `<TableRow`, `<Card` doesn't match `<CardHeader`, etc. The gallery's own files
 * are excluded so demos don't inflate the numbers. Rough by design (a general
 * sense of what's load-bearing), not an exact reference count.
 * Run from frontend/: node components/ui-gallery/gen-callsite-counts.cjs
 */
const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const dir = __dirname;
const FE = path.resolve(dir, "../..");

// Component names come straight from the registry (registered + not-previewable).
const registry = fs.readFileSync(path.join(dir, "registry.tsx"), "utf8");
const names = [...new Set([...registry.matchAll(/name:\s*"([A-Za-z]+)"/g)].map((m) => m[1]))];

const counts = {};
for (const name of names) {
  let n = 0;
  try {
    const out = execSync(`rg -oN --no-filename -g '!components/ui-gallery/**' '<${name}[\\s/>]' app components lib`, {
      cwd: FE,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    });
    n = out ? out.split("\n").filter(Boolean).length : 0;
  } catch {
    // rg exits 1 when there are no matches — that's a legitimate zero.
    n = 0;
  }
  counts[name] = n;
}

const body = names
  .sort()
  .map((name) => `  ${name}: ${counts[name]},`)
  .join("\n");
const out = `// GENERATED by ./gen-callsite-counts.cjs — do not edit by hand.
// Rough count of JSX callsites (\`<Name\`) per component across the frontend,
// excluding the gallery itself. Regenerate after big refactors.
export const callsiteCounts: Record<string, number> = {
${body}
};
`;
fs.writeFileSync(path.join(dir, "callsite-counts.ts"), out);
console.log(`wrote callsite-counts.ts for ${names.length} components`);
console.log(
  names
    .slice()
    .sort((a, b) => counts[b] - counts[a])
    .map((n) => `  ${n}: ${counts[n]}`)
    .join("\n")
);
